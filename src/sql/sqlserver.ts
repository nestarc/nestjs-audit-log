import type { AuditTableSQLOptions } from './index';
import { getSqlServerTableName } from './table-name';

const COLUMNS = [
  ['id', 'uniqueidentifier', 16, 0, 0],
  ['tenant_id', 'nvarchar', -1, 1, 0],
  ['actor_id', 'nvarchar', -1, 1, 0],
  ['actor_type', 'nvarchar', -1, 0, 0],
  ['actor_ip', 'nvarchar', -1, 1, 0],
  ['action', 'nvarchar', -1, 0, 0],
  ['target_type', 'nvarchar', -1, 1, 0],
  ['target_id', 'nvarchar', -1, 1, 0],
  ['source', 'nvarchar', -1, 0, 0],
  ['changes', 'nvarchar', -1, 1, 0],
  ['metadata', 'nvarchar', -1, 1, 0],
  ['result', 'nvarchar', -1, 0, 0],
  ['created_at', 'datetime2', 8, 0, 7],
] as const;

/** Normalize only formatting in expressions generated by this installer. */
function normalizedDefinition(expression: string): string {
  return ["N' '", "N'['", "N']'", "N'('", "N')'", 'NCHAR(9)', 'NCHAR(13)', 'NCHAR(10)'].reduce(
    (sql, character) => `REPLACE(${sql}, ${character}, N'')`,
    `LOWER(${expression})`,
  );
}

export function getSqlServerAuditTableStatements(options: AuditTableSQLOptions): string[] {
  if (options.partitioned || options.ginIndex || (options.enforcement !== undefined && options.enforcement !== 'trigger')) {
    throw new Error(
      '[@nestarc/audit-log] SQL Server audit DDL supports only flat tables with trigger enforcement; ' +
        'partitioned, ginIndex and rule enforcement are not supported.',
    );
  }
  const { schema, table, quoted, qualified } = getSqlServerTableName(options.tableName);
  const incompatibility = `[@nestarc/audit-log] Incompatible SQL Server audit table '${qualified}'.`;
  const expectedColumns = COLUMNS.map(([name, type, length, nullable, scale]) =>
    `    (N'${name}', N'${type}', ${length}, ${nullable}, ${scale})`,
  ).join(',\n');
  const clusteredIndex = `idx_${table}_created`;
  const updateTrigger = `${table}_no_update_trg`;
  const deleteTrigger = `${table}_no_delete_trg`;

  const createTable = `IF SCHEMA_ID(N'${schema}') IS NULL
  THROW 51002, '[@nestarc/audit-log] SQL Server audit schema ${schema} does not exist.', 1;
IF OBJECT_ID(N'${qualified}') IS NOT NULL AND OBJECT_ID(N'${qualified}', N'U') IS NULL
  THROW 51002, '${incompatibility.replaceAll("'", "''")}', 1;
IF OBJECT_ID(N'${qualified}', N'U') IS NULL
BEGIN
  CREATE TABLE ${quoted} (
    [id] UNIQUEIDENTIFIER NOT NULL DEFAULT NEWID(),
    [tenant_id] NVARCHAR(MAX) NULL,
    [actor_id] NVARCHAR(MAX) NULL,
    [actor_type] NVARCHAR(MAX) NOT NULL DEFAULT N'user',
    [actor_ip] NVARCHAR(MAX) NULL,
    [action] NVARCHAR(MAX) NOT NULL,
    [target_type] NVARCHAR(MAX) NULL,
    [target_id] NVARCHAR(MAX) NULL,
    [source] NVARCHAR(MAX) NOT NULL DEFAULT N'manual',
    [changes] NVARCHAR(MAX) NULL,
    [metadata] NVARCHAR(MAX) NULL,
    [result] NVARCHAR(MAX) NOT NULL DEFAULT N'success',
    [created_at] DATETIME2(7) NOT NULL DEFAULT SYSUTCDATETIME(),
    CONSTRAINT [${table}_pkey] PRIMARY KEY NONCLUSTERED ([id])
  );
END;`;

  // Check required columns and write defaults before modifying an existing table.
  const validateTable = `DECLARE @audit_table_id INT = OBJECT_ID(N'${qualified}', N'U');
IF EXISTS (
  SELECT 1 FROM (VALUES
${expectedColumns}
  ) AS expected([name], [type], [length], [nullable], [scale])
  LEFT JOIN sys.columns AS actual ON actual.[object_id] = @audit_table_id AND actual.[name] = expected.[name]
  WHERE actual.[column_id] IS NULL OR TYPE_NAME(actual.[system_type_id]) <> expected.[type]
    OR actual.[max_length] <> expected.[length] OR actual.[is_nullable] <> expected.[nullable]
    OR actual.[scale] <> expected.[scale] OR actual.[is_computed] <> 0 OR actual.[is_identity] <> 0
    OR actual.[generated_always_type] <> 0 OR actual.[user_type_id] <> actual.[system_type_id]
) OR EXISTS (
  SELECT 1 FROM sys.columns AS extra WHERE extra.[object_id] = @audit_table_id
    AND extra.[name] NOT IN (${COLUMNS.map(([name]) => `N'${name}'`).join(', ')})
    AND extra.[is_nullable] = 0 AND extra.[default_object_id] = 0 AND extra.[is_computed] = 0 AND extra.[is_identity] = 0
) OR EXISTS (
  SELECT 1 FROM sys.tables WHERE [object_id] = @audit_table_id
    AND ([is_memory_optimized] <> 0 OR [temporal_type] <> 0 OR [ledger_type] <> 0)
) OR NOT EXISTS (
  SELECT 1 FROM sys.columns AS c JOIN sys.default_constraints AS d ON c.[default_object_id] = d.[object_id]
  WHERE c.[object_id] = @audit_table_id AND c.[name] = N'id'
    AND ${normalizedDefinition('d.[definition]')} = N'newid'
) OR NOT EXISTS (
  SELECT 1 FROM sys.columns AS c JOIN sys.default_constraints AS d ON c.[default_object_id] = d.[object_id]
  WHERE c.[object_id] = @audit_table_id AND c.[name] = N'created_at'
    AND ${normalizedDefinition('d.[definition]')} = N'sysutcdatetime'
) OR NOT EXISTS (
  SELECT 1 FROM sys.indexes AS i WHERE i.[object_id] = @audit_table_id AND i.[is_primary_key] = 1
    AND i.[type] = 2 AND i.[is_disabled] = 0
    AND (SELECT COUNT(*) FROM sys.index_columns AS ic WHERE ic.[object_id] = i.[object_id]
      AND ic.[index_id] = i.[index_id] AND ic.[key_ordinal] > 0) = 1
    AND EXISTS (SELECT 1 FROM sys.index_columns AS ic JOIN sys.columns AS c
      ON c.[object_id] = ic.[object_id] AND c.[column_id] = ic.[column_id]
      WHERE ic.[object_id] = i.[object_id] AND ic.[index_id] = i.[index_id] AND ic.[key_ordinal] = 1 AND c.[name] = N'id')
)
  THROW 51002, '${incompatibility.replaceAll("'", "''")}', 1;
${[updateTrigger, deleteTrigger].map(trigger => `IF OBJECT_ID(N'${schema}.${trigger}') IS NOT NULL AND NOT EXISTS (
  SELECT 1 FROM sys.triggers WHERE [object_id] = OBJECT_ID(N'${schema}.${trigger}') AND [parent_id] = @audit_table_id
)
  THROW 51002, '${incompatibility.replaceAll("'", "''")}', 1;`).join('\n')}`;

  const jsonChecks = ['changes', 'metadata'].map(column => {
    const constraint = `${table}_${column}_json`;
    return {
      validate: `IF EXISTS (
  SELECT 1 FROM sys.check_constraints WHERE [parent_object_id] = OBJECT_ID(N'${qualified}')
    AND [name] = N'${constraint}'
    AND ${normalizedDefinition('[definition]')} <> N'${column}isnullorisjson${column}=1'
)
  THROW 51002, '${incompatibility.replaceAll("'", "''")}', 1;`,
      install: `IF NOT EXISTS (
  SELECT 1 FROM sys.check_constraints WHERE [parent_object_id] = OBJECT_ID(N'${qualified}') AND [name] = N'${constraint}'
)
  ALTER TABLE ${quoted} WITH CHECK ADD CONSTRAINT [${constraint}]
    CHECK ([${column}] IS NULL OR ISJSON([${column}]) = 1);
IF EXISTS (
  SELECT 1 FROM sys.check_constraints WHERE [parent_object_id] = OBJECT_ID(N'${qualified}') AND [name] = N'${constraint}'
    AND ([is_disabled] = 1 OR [is_not_trusted] = 1)
)
  ALTER TABLE ${quoted} WITH CHECK CHECK CONSTRAINT [${constraint}];`,
    };
  });

  const validateIndex = `IF EXISTS (
  SELECT 1 FROM sys.indexes AS i WHERE i.[object_id] = @audit_table_id
    AND (i.[type] = 1 OR i.[name] = N'${clusteredIndex}')
    AND (i.[type] <> 1 OR i.[name] <> N'${clusteredIndex}' OR i.[is_disabled] <> 0
      OR (SELECT COUNT(*) FROM sys.index_columns AS ic WHERE ic.[object_id] = i.[object_id]
        AND ic.[index_id] = i.[index_id] AND ic.[key_ordinal] > 0) <> 2
      OR NOT EXISTS (SELECT 1 FROM sys.index_columns AS ic JOIN sys.columns AS c
        ON c.[object_id] = ic.[object_id] AND c.[column_id] = ic.[column_id]
        WHERE ic.[object_id] = i.[object_id] AND ic.[index_id] = i.[index_id] AND ic.[key_ordinal] = 1
          AND ic.[is_descending_key] = 0 AND c.[name] = N'created_at')
      OR NOT EXISTS (SELECT 1 FROM sys.index_columns AS ic JOIN sys.columns AS c
        ON c.[object_id] = ic.[object_id] AND c.[column_id] = ic.[column_id]
        WHERE ic.[object_id] = i.[object_id] AND ic.[index_id] = i.[index_id] AND ic.[key_ordinal] = 2
          AND ic.[is_descending_key] = 0 AND c.[name] = N'id'))
)
  THROW 51002, '${incompatibility.replaceAll("'", "''")}', 1;`;
  const index = `IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE [object_id] = OBJECT_ID(N'${qualified}') AND [name] = N'${clusteredIndex}')
  CREATE CLUSTERED INDEX [${clusteredIndex}] ON ${quoted} ([created_at], [id]);`;

  const triggers = (['UPDATE', 'DELETE'] as const).flatMap(operation => {
    const trigger = operation === 'UPDATE' ? updateTrigger : deleteTrigger;
    return [
      `CREATE OR ALTER TRIGGER [${schema}].[${trigger}]
ON ${quoted} AFTER ${operation} AS
BEGIN
  SET NOCOUNT ON;
  IF EXISTS (SELECT 1 FROM deleted)
    THROW 51001, '[@nestarc/audit-log] ${operation} blocked on append-only audit table ${qualified}.', 1;
END;`,
      `ENABLE TRIGGER [${schema}].[${trigger}] ON ${quoted};`,
    ];
  });
  return [
    createTable,
    [validateTable, ...jsonChecks.map(check => check.validate), validateIndex].join('\n'),
    jsonChecks.map(check => check.install).join('\n'),
    index,
    ...triggers,
  ];
}
